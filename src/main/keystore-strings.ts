export function fillKeystoreText(text: string, values: Record<string, string>): string {
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}

/** The language's own, or its region's, or English. */
export function keystoreTextFor(language: string): KeystoreText {
  const lower = language.toLowerCase();
  if (lower === 'zh-tw' || lower === 'zh-hk' || lower === 'zh-mo' || lower.startsWith('zh-hant')) return KEYSTORE_TEXT['zh-TW'];
  const base = lower.split(/[-_]/)[0];
  if (base === 'no' || base === 'nn') return KEYSTORE_TEXT.nb;
  return Object.hasOwn(KEYSTORE_TEXT, base) ? KEYSTORE_TEXT[base] : KEYSTORE_TEXT.en;
}
